CREATE FUNCTION public.validate_restaurant_deal_reference() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
DECLARE ds uuid; ps uuid;
BEGIN
 SELECT shop_id INTO ds FROM public.restaurant_deals WHERE id=NEW.deal_id;
 SELECT shop_id INTO ps FROM public.products WHERE id=NEW.product_id AND is_active;
 IF ds IS NULL OR ps IS NULL OR NEW.shop_id<>ds OR NEW.shop_id<>ps THEN RAISE EXCEPTION 'deal component belongs to another shop or is unavailable'; END IF;
 RETURN NEW;
END $$;
CREATE FUNCTION public.prevent_restaurant_deal_shop_change() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
BEGIN IF NEW.shop_id IS DISTINCT FROM OLD.shop_id THEN RAISE EXCEPTION 'shop_id is immutable'; END IF; RETURN NEW; END $$;
CREATE TRIGGER restaurant_deals_shop_immutable BEFORE UPDATE OF shop_id ON public.restaurant_deals FOR EACH ROW EXECUTE FUNCTION public.prevent_restaurant_deal_shop_change();
CREATE TRIGGER restaurant_deal_items_shop_immutable BEFORE UPDATE OF shop_id ON public.restaurant_deal_items FOR EACH ROW EXECUTE FUNCTION public.prevent_restaurant_deal_shop_change();
CREATE TRIGGER restaurant_deal_items_validate BEFORE INSERT OR UPDATE ON public.restaurant_deal_items FOR EACH ROW EXECUTE FUNCTION public.validate_restaurant_deal_reference();

CREATE FUNCTION public.manage_restaurant_deal(p_operation text,p_deal_id uuid,p_name text,p_description text,p_deal_price numeric,p_product_ids uuid[],p_quantities numeric[])
RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE s uuid:=public.get_user_shop_id(); d uuid; i integer;
BEGIN
 IF s IS NULL OR NOT public.industry_module_enabled(s,'menu') THEN RAISE EXCEPTION 'unauthorized module'; END IF;
 IF p_operation='archive' THEN UPDATE public.restaurant_deals SET is_active=false,updated_at=now() WHERE id=p_deal_id AND shop_id=s AND is_active RETURNING id INTO d; IF d IS NULL THEN RAISE EXCEPTION 'active deal not found'; END IF; RETURN d; END IF;
 IF p_operation NOT IN('create','update') OR length(trim(COALESCE(p_name,'')))=0 OR p_deal_price<0 OR COALESCE(array_length(p_product_ids,1),0)=0 OR array_length(p_product_ids,1)<>array_length(p_quantities,1) THEN RAISE EXCEPTION 'invalid deal details'; END IF;
 IF EXISTS(SELECT 1 FROM generate_subscripts(p_quantities,1) x WHERE p_quantities[x]<=0) THEN RAISE EXCEPTION 'invalid deal quantity'; END IF;
 IF (SELECT count(*) FROM public.products WHERE shop_id=s AND is_active AND id=ANY(p_product_ids))<>array_length(p_product_ids,1) OR (SELECT count(DISTINCT x) FROM unnest(p_product_ids)x)<>array_length(p_product_ids,1) THEN RAISE EXCEPTION 'deal contains unavailable, duplicate, or cross-shop products'; END IF;
 IF p_operation='create' THEN INSERT INTO public.restaurant_deals(shop_id,name,description,deal_price) VALUES(s,trim(p_name),NULLIF(trim(p_description),''),p_deal_price) RETURNING id INTO d;
 ELSE UPDATE public.restaurant_deals SET name=trim(p_name),description=NULLIF(trim(p_description),''),deal_price=p_deal_price,updated_at=now() WHERE id=p_deal_id AND shop_id=s RETURNING id INTO d; IF d IS NULL THEN RAISE EXCEPTION 'deal not found'; END IF; DELETE FROM public.restaurant_deal_items WHERE deal_id=d AND shop_id=s; END IF;
 FOR i IN 1..array_length(p_product_ids,1) LOOP INSERT INTO public.restaurant_deal_items(shop_id,deal_id,product_id,quantity) VALUES(s,d,p_product_ids[i],p_quantities[i]); END LOOP;
 RETURN d;
END $$;

CREATE FUNCTION public.set_restaurant_deal_active(p_deal_id uuid,p_active boolean) RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE s uuid:=public.get_user_shop_id(); BEGIN
 IF s IS NULL OR NOT public.industry_module_enabled(s,'menu') THEN RAISE EXCEPTION 'unauthorized module'; END IF;
 UPDATE public.restaurant_deals SET is_active=p_active,updated_at=now() WHERE id=p_deal_id AND shop_id=s; IF NOT FOUND THEN RAISE EXCEPTION 'deal not found'; END IF;
END $$;

CREATE FUNCTION public.add_restaurant_deal_to_order(p_order_id uuid,p_deal_id uuid,p_quantity integer,p_notes text) RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE
 s uuid:=public.get_user_shop_id(); d public.restaurant_deals%ROWTYPE; c record; regular numeric;
 line_quantity numeric; line_total numeric; allocated numeric:=0; component_index integer:=0; component_count integer;
BEGIN
 IF s IS NULL OR NOT public.industry_module_enabled(s,'restaurant_orders') THEN RAISE EXCEPTION 'unauthorized module'; END IF;
 IF p_quantity<1 THEN RAISE EXCEPTION 'deal quantity must be positive'; END IF;
 PERFORM 1 FROM public.restaurant_orders WHERE id=p_order_id AND shop_id=s AND sale_id IS NULL AND status='pending' FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'active order not found'; END IF;
 SELECT * INTO d FROM public.restaurant_deals WHERE id=p_deal_id AND shop_id=s AND is_active FOR SHARE;
 IF NOT FOUND THEN RAISE EXCEPTION 'active deal not found'; END IF;
 SELECT sum(di.quantity*p.selling_price),count(*) INTO regular,component_count FROM public.restaurant_deal_items di JOIN public.products p ON p.id=di.product_id AND p.shop_id=s AND p.is_active WHERE di.deal_id=d.id;
 IF regular IS NULL OR regular<=0 OR component_count=0 THEN RAISE EXCEPTION 'deal has no sellable components'; END IF;
 FOR c IN SELECT di.product_id,di.quantity,p.selling_price FROM public.restaurant_deal_items di JOIN public.products p ON p.id=di.product_id AND p.shop_id=s AND p.is_active WHERE di.deal_id=d.id ORDER BY di.id LOOP
  component_index:=component_index+1;
  line_quantity:=c.quantity*p_quantity;
  IF component_index=component_count THEN line_total:=d.deal_price*p_quantity-allocated;
  ELSE line_total:=round(d.deal_price*p_quantity*(c.quantity*c.selling_price/regular),4); allocated:=allocated+line_total; END IF;
  INSERT INTO public.restaurant_order_items(shop_id,order_id,product_id,quantity,unit_price,notes)
  VALUES(s,p_order_id,c.product_id,line_quantity,line_total/line_quantity,'Deal: '||d.name||CASE WHEN NULLIF(trim(p_notes),'') IS NULL THEN '' ELSE ' - '||trim(p_notes) END)
  ON CONFLICT(order_id,product_id) DO UPDATE SET unit_price=(public.restaurant_order_items.quantity*public.restaurant_order_items.unit_price+EXCLUDED.quantity*EXCLUDED.unit_price)/(public.restaurant_order_items.quantity+EXCLUDED.quantity),quantity=public.restaurant_order_items.quantity+EXCLUDED.quantity,notes=concat_ws(' | ',public.restaurant_order_items.notes,EXCLUDED.notes);
 END LOOP;
 UPDATE public.restaurant_orders SET total_amount=(SELECT COALESCE(sum(oi.quantity*oi.unit_price),0) FROM public.restaurant_order_items oi WHERE order_id=p_order_id),updated_at=now() WHERE id=p_order_id;
END $$;

