CREATE FUNCTION public.create_restaurant_order(p_order_type text,p_table_id uuid,p_guest_count integer,p_notes text)
RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE s uuid:=public.get_user_shop_id(); o uuid;
BEGIN
 IF s IS NULL OR NOT public.industry_module_enabled(s,'restaurant_orders') THEN RAISE EXCEPTION 'unauthorized module'; END IF;
 IF p_order_type NOT IN('dine_in','takeaway') OR (p_order_type='dine_in' AND p_table_id IS NULL) OR (p_order_type='takeaway' AND p_table_id IS NOT NULL) OR (p_guest_count IS NOT NULL AND p_guest_count<1) THEN RAISE EXCEPTION 'invalid order details'; END IF;
 IF p_table_id IS NOT NULL THEN
  PERFORM 1 FROM public.restaurant_tables WHERE id=p_table_id AND shop_id=s AND status='available' FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'table is unavailable or belongs to another shop'; END IF;
 END IF;
 INSERT INTO public.restaurant_orders(shop_id,table_id,order_type,guest_count,notes,status) VALUES(s,p_table_id,p_order_type,p_guest_count,NULLIF(trim(p_notes),''),'pending') RETURNING id INTO o;
 IF p_table_id IS NOT NULL THEN UPDATE public.restaurant_tables SET status='occupied' WHERE id=p_table_id AND shop_id=s; END IF;
 RETURN o;
END $$;

CREATE FUNCTION public.adjust_restaurant_order_item(p_order_id uuid,p_product_id uuid,p_delta integer,p_notes text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE s uuid:=public.get_user_shop_id(); current_quantity numeric; price numeric;
BEGIN
 IF s IS NULL OR NOT public.industry_module_enabled(s,'restaurant_orders') THEN RAISE EXCEPTION 'unauthorized module'; END IF;
 IF p_delta=0 THEN RAISE EXCEPTION 'quantity adjustment cannot be zero'; END IF;
 PERFORM 1 FROM public.restaurant_orders WHERE id=p_order_id AND shop_id=s AND sale_id IS NULL AND status='pending' FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'open order not found'; END IF;
 SELECT selling_price INTO price FROM public.products WHERE id=p_product_id AND shop_id=s AND is_active FOR SHARE;
 IF price IS NULL THEN RAISE EXCEPTION 'active menu item not found'; END IF;
 SELECT quantity INTO current_quantity FROM public.restaurant_order_items WHERE order_id=p_order_id AND product_id=p_product_id AND shop_id=s FOR UPDATE;
 IF current_quantity IS NULL THEN
  IF p_delta<1 THEN RAISE EXCEPTION 'order item not found'; END IF;
  INSERT INTO public.restaurant_order_items(shop_id,order_id,product_id,quantity,unit_price,notes) VALUES(s,p_order_id,p_product_id,p_delta,price,NULLIF(trim(p_notes),''));
 ELSIF current_quantity+p_delta<=0 THEN
  DELETE FROM public.restaurant_order_items WHERE order_id=p_order_id AND product_id=p_product_id AND shop_id=s;
 ELSE
  UPDATE public.restaurant_order_items SET quantity=current_quantity+p_delta,notes=COALESCE(NULLIF(trim(p_notes),''),notes) WHERE order_id=p_order_id AND product_id=p_product_id AND shop_id=s;
 END IF;
 UPDATE public.restaurant_orders SET total_amount=(SELECT COALESCE(sum(quantity*unit_price),0) FROM public.restaurant_order_items WHERE order_id=p_order_id),updated_at=now() WHERE id=p_order_id AND shop_id=s;
END $$;

CREATE OR REPLACE FUNCTION public.complete_restaurant_order(p_order_id uuid,p_payment_method text)
RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE s uuid:=public.get_user_shop_id(); sale uuid; total numeric; table_ref uuid; item record;
BEGIN
 IF s IS NULL OR NOT public.industry_module_enabled(s,'restaurant_orders') THEN RAISE EXCEPTION 'unauthorized module'; END IF;
 SELECT table_id,total_amount INTO table_ref,total FROM public.restaurant_orders WHERE id=p_order_id AND shop_id=s AND status='pending' AND sale_id IS NULL FOR UPDATE;
 IF NOT FOUND OR total<=0 THEN RAISE EXCEPTION 'open order has no payable items or is already paid'; END IF;
 FOR item IN SELECT oi.quantity,p.name,p.quantity stock FROM public.restaurant_order_items oi JOIN public.products p ON p.id=oi.product_id AND p.shop_id=s WHERE oi.order_id=p_order_id FOR UPDATE OF p
 LOOP IF item.stock<item.quantity THEN RAISE EXCEPTION 'insufficient stock for %',item.name; END IF; END LOOP;
 INSERT INTO public.sales(shop_id,user_id,customer_name,subtotal,discount,tax,total_amount,status) VALUES(s,auth.uid(),'Restaurant Guest',total,0,0,total,'completed') RETURNING id INTO sale;
 INSERT INTO public.sale_items(sale_id,shop_id,product_id,product_name,quantity,unit_price,total_price)
 SELECT sale,s,oi.product_id,CASE WHEN oi.notes LIKE 'Deal: %' THEN p.name||' ('||split_part(oi.notes,' - ',1)||')' ELSE p.name END,oi.quantity,oi.unit_price,oi.quantity*oi.unit_price FROM public.restaurant_order_items oi JOIN public.products p ON p.id=oi.product_id WHERE oi.order_id=p_order_id;
 UPDATE public.products p SET quantity=p.quantity-oi.quantity FROM public.restaurant_order_items oi WHERE oi.order_id=p_order_id AND p.id=oi.product_id AND p.shop_id=s;
 INSERT INTO public.payments(sale_id,shop_id,amount,method) VALUES(sale,s,total,p_payment_method);
 UPDATE public.restaurant_orders SET sale_id=sale,status='completed',updated_at=now() WHERE id=p_order_id AND shop_id=s AND sale_id IS NULL;
 IF NOT FOUND THEN RAISE EXCEPTION 'order was already paid'; END IF;
 IF table_ref IS NOT NULL THEN UPDATE public.restaurant_tables SET status='available' WHERE id=table_ref AND shop_id=s; END IF;
 RETURN sale;
END $$;
CREATE OR REPLACE FUNCTION public.shop_type_default_modules(p_shop_type text)
RETURNS text[] LANGUAGE plpgsql STABLE SET search_path='' AS $$
BEGIN
  CASE lower(COALESCE(p_shop_type,'retail'))
    WHEN 'restaurant' THEN RETURN ARRAY['dashboard','pos','sales','menu','restaurant_tables','restaurant_orders','customers','expenses','reports'];
    WHEN 'pharmacy' THEN RETURN ARRAY['dashboard','pos','products','medicines','customers','categories','medicine_batches','medicine_expiry','prescriptions','suppliers','purchases','sales','reports'];
    WHEN 'grocery' THEN RETURN ARRAY['dashboard','pos','products','categories','inventory','sales','purchases','suppliers','customers','expenses','reports','medicine_batches','medicine_expiry'];
    ELSE RETURN ARRAY['dashboard','pos','products','categories','inventory','sales','purchases','suppliers','customers','expenses','reports'];
  END CASE;
END $$;

